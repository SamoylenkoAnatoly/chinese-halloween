"""Генератор пиксельных персонажей Двора Тихой Луны.

Рисует на пиксельной сетке (клетка = 1 единица viewBox) и рендерит в SVG
в технике wizard.svg: shape-rendering="crispEdges", каждая группа цвета —
<path> из квадратов 1x1 (M{x} {y}h1v1h-1z).
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "shared" / "characters"
OUT.mkdir(parents=True, exist_ok=True)


class Grid:
    def __init__(self, w, h):
        self.w, self.h = w, h
        self.c = [[None] * w for _ in range(h)]

    def px(self, x, y, col):
        if 0 <= x < self.w and 0 <= y < self.h:
            self.c[y][x] = col

    def rect(self, x, y, w, h, col):
        for j in range(y, y + h):
            for i in range(x, x + w):
                self.px(i, j, col)

    def hline(self, x, y, w, col):
        self.rect(x, y, w, 1, col)

    def vline(self, x, y, h, col):
        self.rect(x, y, 1, h, col)

    def ellipse(self, cx, cy, rx, ry, col):
        for j in range(self.h):
            for i in range(self.w):
                dx = (i - cx) / rx
                dy = (j - cy) / ry
                if dx * dx + dy * dy <= 1.02:
                    self.px(i, j, col)

    def mirror_lr(self):
        """Копирует левую половину в правую зеркально (для симметрии лиц)."""
        mid = self.w // 2
        for j in range(self.h):
            for i in range(mid):
                self.c[j][self.w - 1 - i] = self.c[j][i]

    def render_svg(self, palette, name, desc):
        paths = []
        for key, hexcol in palette.items():
            cells = []
            for j in range(self.h):
                run = None
                for i in range(self.w + 1):
                    cur = key if i < self.w and self.c[j][i] == key else None
                    if cur != run:
                        if run:
                            cells.append("M{0} {1}h{2}v1h-{2}z".format(run, j, i - run))
                        run = i if cur else None
            if cells:
                paths.append('<path fill="{0}" d="{1}"/>'.format(hexcol, "".join(cells)))
        svg = (
            '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {0} {1}" '
            'width="{0}" height="{1}" shape-rendering="crispEdges" role="img" '
            'aria-label="{2}">\n{3}\n</svg>\n'
        ).format(self.w, self.h, desc, "\n".join(paths))
        (OUT / name).write_text(svg, encoding="utf-8")
        print(name, "OK", self.w, "x", self.h)


